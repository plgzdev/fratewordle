function hashDateSeed(dateStr: string): number {
	let hash = 0;
	for (let i = 0; i < dateStr.length; i++) {
		hash = (hash * 31 + dateStr.charCodeAt(i)) >>> 0;
	}
	return hash;
}

export function getAutoGeneratedChallenges(dateStr: string) {
	const seed = hashDateSeed(dateStr);

	const pickedWord = FALLBACK_WORDS[seed % FALLBACK_WORDS.length];
	const pickedPhrase = FALLBACK_PHRASES[seed % FALLBACK_PHRASES.length];

	return {
		word: {
			word: normalizeSpanish(pickedWord.word),
			hint: pickedWord.hint
		},
		phrase: {
			word: normalizeSpanish(pickedPhrase.word),
			hint: pickedPhrase.hint
		}
	};
}