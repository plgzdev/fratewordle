export function normalizeSpanish(text: string): string {
	return text
		.trim()
		.toUpperCase()
		.replace(/Á/g, 'A')
		.replace(/É/g, 'E')
		.replace(/Í/g, 'I')
		.replace(/Ó/g, 'O')
		.replace(/Ú/g, 'U')
		.replace(/Ü/g, 'U');
}

