const MAX_ATTEMPTS = 6;
const LETTER_REGEX = /^[A-ZÑ]$/;

function evaluateWordGuess(guess: string, target: string): LetterState[] {
	const len = target.length;
	const result: LetterState[] = Array(len).fill('absent');
	const targetChars = target.split('');
	const guessChars = guess.split('');
	const used = Array(len).fill(false);

	for (let i = 0; i < len; i++) {
		if (guessChars[i] === targetChars[i]) {
			result[i] = 'correct';
			used[i] = true;
		}
	}

	for (let i = 0; i < len; i++) {
		if (result[i] === 'correct') continue;
		const idx = targetChars.findIndex((c, j) => !used[j] && c === guessChars[i]);
		if (idx !== -1) {
			result[i] = 'present';
			used[idx] = true;
		}
	}

	return result;
}

function buildMaskedPhrase(target: string, guessedLetters: string[], revealAll: boolean): string[] {
	const guessedSet = new Set(guessedLetters);
	return target.split('').map((char) => {
		if (!LETTER_REGEX.test(char)) return char;
		if (revealAll || guessedSet.has(char)) return char;
		return '_';
	});
}

function sanitizeDisplayName(name: string): string {
	// Si Better Auth puso el correo como nombre por defecto, ocultamos el @dominio
	return name.includes('@') ? name.split('@')[0] : name;
}

function getPreviousDateStr(dateStr: string): string {
	const [y, m, d] = dateStr.split('-').map(Number);
	const prev = new Date(Date.UTC(y, m - 1, d - 1));
	return prev.toISOString().slice(0, 10);
}

async function syncUserDailyStreak(userId: string, todayStr: string) {
	// Consultar todos los intentos del usuario cruzados con la fecha del reto
	const rows = await db
		.select({
			dateStr: dailyWords.dateStr,
			status: gameAttempts.status
		})
		.from(gameAttempts)
		.innerJoin(dailyWords, eq(gameAttempts.wordId, dailyWords.id))
		.where(eq(gameAttempts.userId, userId));

	// Agrupar estados por día
	const dayMap = new Map<string, { hasWin: boolean; allLost: boolean; count: number }>();
	for (const r of rows) {
		const entry = dayMap.get(r.dateStr) ?? { hasWin: false, allLost: true, count: 0 };
		entry.count += 1;
		if (r.status === 'won') {
			entry.hasWin = true;
			entry.allLost = false;
		} else if (r.status === 'playing') {
			entry.allLost = false;
		}
		dayMap.set(r.dateStr, entry);
	}

	// Contar días consecutivos con al menos 1 victoria hacia atrás desde hoy (o ayer si hoy aún no gana)
	let streak = 0;
	let cursor = todayStr;

	const todayEntry = dayMap.get(todayStr);
	if (!todayEntry?.hasWin) {
		// Si hoy ya perdió ambos modos (2 derrotas), la racha se corta a 0 de inmediato
		if (todayEntry && todayEntry.count >= 2 && todayEntry.allLost) {
			await db.update(user).set({ currentStreak: 0 }).where(eq(user.id, userId));
			return;
		}
		// Si aún no gana hoy pero sigue jugando, verificamos desde ayer
		cursor = getPreviousDateStr(todayStr);
	}

	while (dayMap.get(cursor)?.hasWin) {
		streak += 1;
		cursor = getPreviousDateStr(cursor);
	}

	await db
		.update(user)
		.set({
			currentStreak: streak,
			maxStreak: sql`GREATEST(${user.maxStreak}, ${streak})`
		})
		.where(eq(user.id, userId));
}

export async function getInitialGameData() {
	await connection();
	const session = await auth.api.getSession({ headers: await headers() });
	const today = getLocalTodayStr();

	const todaysChallenges = await db
		.select()
		.from(dailyWords)
		.where(eq(dailyWords.dateStr, today));

	let wordDaily = todaysChallenges.find((c) => c.mode === 'word') ?? null;
	let phraseDaily = todaysChallenges.find((c) => c.mode === 'phrase') ?? null;

	// Respaldo automático si hoy no hay palabra o frase programada
	if (!wordDaily || !phraseDaily) {
		const fallback = getAutoGeneratedChallenges(today);

		if (!wordDaily) {
			const [insertedWord] = await db
				.insert(dailyWords)
				.values({
					dateStr: today,
					mode: 'word',
					word: fallback.word.word,
					hint: fallback.word.hint
				})
				.returning();
			wordDaily = insertedWord ?? null;
		}

		if (!phraseDaily) {
			const [insertedPhrase] = await db
				.insert(dailyWords)
				.values({
					dateStr: today,
					mode: 'phrase',
					word: fallback.phrase.word,
					hint: fallback.phrase.hint
				})
				.returning();
			phraseDaily = insertedPhrase ?? null;
		}
	}

	if (session) {
		await syncUserDailyStreak(session.user.id, today);
	}

	const userAttempts = session
		? await db.select().from(gameAttempts).where(eq(gameAttempts.userId, session.user.id))
		: [];

	// Estado Modo Palabra
	let wordState = null;
	if (wordDaily) {
		const target = normalizeSpanish(wordDaily.word);
		const attempt = userAttempts.find((a) => a.wordId === wordDaily.id);
		const guesses = attempt?.guesses ?? [];
		const status = attempt?.status ?? 'playing';

		wordState = {
			id: wordDaily.id,
			dateStr: today,
			length: target.length,
			hint: wordDaily.hint,
			guesses,
			evaluations: guesses.map((g) => evaluateWordGuess(g, target)),
			status,
			score: attempt?.score ?? 0,
			solution: status !== 'playing' ? target : null
		};
	}

	// Estado Modo Frase (Ahorcado)
	let phraseState = null;
	if (phraseDaily) {
		const target = normalizeSpanish(phraseDaily.word);
		const attempt = userAttempts.find((a) => a.wordId === phraseDaily.id);
		const guessedLetters = attempt?.guesses ?? [];
		const status = attempt?.status ?? 'playing';
		const wrongLetters = guessedLetters.filter((l) => !target.includes(l));

		phraseState = {
			id: phraseDaily.id,
			dateStr: today,
			hint: phraseDaily.hint,
			maskedChars: buildMaskedPhrase(target, guessedLetters, status !== 'playing'),
			guessedLetters,
			wrongLetters,
			status,
			score: attempt?.score ?? 0,
			solution: status !== 'playing' ? target : null
		};
	}

	// Fechas límite (YYYY-MM-DD) para Diario, Semanal (Lunes a Hoy) y Mensual (Día 1 a Hoy)
	const [y, m, d] = today.split('-').map(Number);
	const todayUtc = new Date(Date.UTC(y, m - 1, d));
	const dayOfWeek = todayUtc.getUTCDay(); // 0 = Dom, 1 = Lun, ..., 6 = Sáb
	const diffToMonday = dayOfWeek === 0 ? 6 : dayOfWeek - 1;
	const mondayUtc = new Date(Date.UTC(y, m - 1, d - diffToMonday));

	const weekStartStr = mondayUtc.toISOString().slice(0, 10);
	const monthStartStr = `${String(y).padStart(4, '0')}-${String(m).padStart(2, '0')}-01`;

	async function buildLeaderboard(minDateStr: string) {
		const ptsExpr =
			sql<number>`coalesce(sum(case when ${dailyWords.dateStr} >= ${minDateStr} then ${gameAttempts.score} else 0 end), 0)`.mapWith(
				Number
			);
		const wonExpr =
			sql<number>`count(case when ${dailyWords.dateStr} >= ${minDateStr} and ${gameAttempts.status} = 'won' then 1 end)`.mapWith(
				Number
			);
		const secExpr =
			sql<number>`coalesce(sum(case when ${dailyWords.dateStr} >= ${minDateStr} then extract(epoch from (${gameAttempts.finishedAt} - ${gameAttempts.startedAt})) else 0 end), 999999)`.mapWith(
				Number
			);

		const rows = await db
			.select({
				id: user.id,
				name: user.name,
				currentStreak: user.currentStreak,
				maxStreak: user.maxStreak,
				totalPoints: ptsExpr,
				gamesWon: wonExpr,
				totalSeconds: secExpr
			})
			.from(user)
			.leftJoin(gameAttempts, eq(user.id, gameAttempts.userId))
			.leftJoin(dailyWords, eq(gameAttempts.wordId, dailyWords.id))
			.groupBy(user.id)
			.orderBy(desc(ptsExpr), desc(wonExpr), asc(secExpr));

		return rows.map((row) => ({
			...row,
			name: sanitizeDisplayName(row.name)
		}));
	}

	const [dailyLeaderboard, weeklyLeaderboard, monthlyLeaderboard] = await Promise.all([
		buildLeaderboard(today),
		buildLeaderboard(weekStartStr),
		buildLeaderboard(monthStartStr)
	]);

	const currentUserRow = session
		? await db
				.select({
					email: user.email,
					currentStreak: user.currentStreak,
					maxStreak: user.maxStreak
				})
				.from(user)
				.where(eq(user.id, session.user.id))
				.then((r) => r[0])
		: null;

	const allTimeStats = session
		? await db
				.select({
					totalPoints: sql<number>`coalesce(sum(${gameAttempts.score}), 0)`.mapWith(Number),
					gamesWon: sql<number>`count(case when ${gameAttempts.status} = 'won' then 1 end)`.mapWith(Number),
					gamesPlayed: sql<number>`count(case when ${gameAttempts.status} != 'playing' then 1 end)`.mapWith(Number)
				})
				.from(gameAttempts)
				.where(eq(gameAttempts.userId, session.user.id))
				.then((r) => r[0])
		: null;

	return {
		user: session
			? {
					id: session.user.id,
					name: sanitizeDisplayName(session.user.name),
					email: currentUserRow?.email ?? session.user.email,
					currentStreak: currentUserRow?.currentStreak ?? 0,
					maxStreak: currentUserRow?.maxStreak ?? 0,
					totalPoints: allTimeStats?.totalPoints ?? 0,
					gamesWon: allTimeStats?.gamesWon ?? 0,
					gamesPlayed: allTimeStats?.gamesPlayed ?? 0
				}
			: null,
		wordState,
		phraseState,
		leaderboards: {
			daily: dailyLeaderboard,
			weekly: weeklyLeaderboard,
			monthly: monthlyLeaderboard
		}
	};
}

export async function submitWordGuess(guessRaw: string, guestGuesses: string[] = []) {
	const session = await auth.api.getSession({ headers: await headers() });
	const today = getLocalTodayStr();

	const [daily] = await db
		.select()
		.from(dailyWords)
		.where(and(eq(dailyWords.dateStr, today), eq(dailyWords.mode, 'word')));

	if (!daily) return { error: 'NO_WORD_TODAY' as const };

	const target = normalizeSpanish(daily.word);
	const guess = normalizeSpanish(guessRaw);

	if (guess.length !== target.length) return { error: 'INVALID_LENGTH' as const };
	if (guess !== target && !isValidSpanishWord(guess, target.length)) {
		return { error: 'NOT_IN_DICTIONARY' as const };
	}

	// Flujo INVITADO (sin sesión)
	if (!session) {
		if (guestGuesses.length >= MAX_ATTEMPTS) return { error: 'ALREADY_FINISHED' as const };
		const updatedGuesses = [...guestGuesses, guess];
		const evaluation = evaluateWordGuess(guess, target);
		const won = guess === target;
		const lost = !won && updatedGuesses.length >= MAX_ATTEMPTS;
		const status = won ? 'won' : lost ? 'lost' : 'playing';
		const pointsTable: Record<number, number> = { 1: 100, 2: 85, 3: 70, 4: 55, 5: 40, 6: 25 };
		const score = won ? (pointsTable[updatedGuesses.length] ?? 0) : 0;

		return {
			ok: true as const,
			guess,
			evaluation,
			status,
			score,
			solution: status !== 'playing' ? target : null
		};
	}

	// Flujo REGISTRADO (guarda en Supabase)
	let [attempt] = await db
		.select()
		.from(gameAttempts)
		.where(and(eq(gameAttempts.userId, session.user.id), eq(gameAttempts.wordId, daily.id)));

	if (!attempt) {
		[attempt] = await db
			.insert(gameAttempts)
			.values({ userId: session.user.id, wordId: daily.id, guesses: [] })
			.returning();
	}

	if (attempt.status !== 'playing') return { error: 'ALREADY_FINISHED' as const };

	const updatedGuesses = [...attempt.guesses, guess];
	const evaluation = evaluateWordGuess(guess, target);
	const won = guess === target;
	const lost = !won && updatedGuesses.length >= MAX_ATTEMPTS;
	const status = won ? 'won' : lost ? 'lost' : 'playing';

	const pointsTable: Record<number, number> = { 1: 100, 2: 85, 3: 70, 4: 55, 5: 40, 6: 25 };
	const score = won ? (pointsTable[updatedGuesses.length] ?? 0) : 0;

	await db
		.update(gameAttempts)
		.set({
			guesses: updatedGuesses,
			status,
			score,
			finishedAt: status !== 'playing' ? new Date() : null
		})
		.where(eq(gameAttempts.id, attempt.id));

	if (status !== 'playing') {
		await syncUserDailyStreak(session.user.id, today);
	}

	return {
		ok: true as const,
		guess,
		evaluation,
		status,
		score,
		solution: status !== 'playing' ? target : null
	};
}

export async function submitPhraseLetter(letterRaw: string, guestLetters: string[] = []) {
	const session = await auth.api.getSession({ headers: await headers() });
	const letter = normalizeSpanish(letterRaw);

	if (!LETTER_REGEX.test(letter)) return { error: 'INVALID_LETTER' as const };

	const today = getLocalTodayStr();
	const [daily] = await db
		.select()
		.from(dailyWords)
		.where(and(eq(dailyWords.dateStr, today), eq(dailyWords.mode, 'phrase')));

	if (!daily) return { error: 'NO_PHRASE_TODAY' as const };

	const target = normalizeSpanish(daily.word);

	// Flujo INVITADO (sin sesión)
	if (!session) {
		if (guestLetters.includes(letter)) return { error: 'ALREADY_GUESSED' as const };
		const updatedGuesses = [...guestLetters, letter];
		const wrongLetters = updatedGuesses.filter((l) => !target.includes(l));
		const allLettersFound = target
			.split('')
			.filter((c) => LETTER_REGEX.test(c))
			.every((c) => updatedGuesses.includes(c));

		const won = allLettersFound;
		const lost = !won && wrongLetters.length >= MAX_ATTEMPTS;
		const status = won ? 'won' : lost ? 'lost' : 'playing';
		const score = won ? Math.max(25, 100 - wrongLetters.length * 15) : 0;

		return {
			ok: true as const,
			maskedChars: buildMaskedPhrase(target, updatedGuesses, status !== 'playing'),
			guessedLetters: updatedGuesses,
			wrongLetters,
			status,
			score,
			solution: status !== 'playing' ? target : null
		};
	}

	// Flujo REGISTRADO (guarda en Supabase)
	let [attempt] = await db
		.select()
		.from(gameAttempts)
		.where(and(eq(gameAttempts.userId, session.user.id), eq(gameAttempts.wordId, daily.id)));

	if (!attempt) {
		[attempt] = await db
			.insert(gameAttempts)
			.values({ userId: session.user.id, wordId: daily.id, guesses: [] })
			.returning();
	}

	if (attempt.status !== 'playing') return { error: 'ALREADY_FINISHED' as const };
	if (attempt.guesses.includes(letter)) return { error: 'ALREADY_GUESSED' as const };

	const updatedGuesses = [...attempt.guesses, letter];
	const letterGuesses = updatedGuesses.filter((g) => !g.startsWith('SOLVE:'));
	const wrongResolutions = updatedGuesses.filter((g) => g.startsWith('SOLVE:')).length;
	const wrongLetters = [
		...letterGuesses.filter((l) => !target.includes(l)),
		...Array(wrongResolutions).fill('✕')
	];
	const allLettersFound = target
		.split('')
		.filter((c) => LETTER_REGEX.test(c))
		.every((c) => letterGuesses.includes(c));

	const won = allLettersFound;
	const lost = !won && wrongLetters.length >= MAX_ATTEMPTS;
	const status = won ? 'won' : lost ? 'lost' : 'playing';

	const score = won ? Math.max(25, 100 - wrongLetters.length * 15) : 0;

	await db
		.update(gameAttempts)
		.set({
			guesses: updatedGuesses,
			status,
			score,
			finishedAt: status !== 'playing' ? new Date() : null
		})
		.where(eq(gameAttempts.id, attempt.id));

	if (status !== 'playing') {
		await syncUserDailyStreak(session.user.id, today);
	}

	return {
		ok: true as const,
		maskedChars: buildMaskedPhrase(target, letterGuesses, status !== 'playing'),
		guessedLetters: letterGuesses,
		wrongLetters,
		status,
		score,
		solution: status !== 'playing' ? target : null
	};
}

export async function solvePhraseGuess(
	phraseGuessRaw: string,
	guestLetters: string[] = [],
	guestWrongResolutions = 0
) {
	const session = await auth.api.getSession({ headers: await headers() });
	const today = getLocalTodayStr();

	const [daily] = await db
		.select()
		.from(dailyWords)
		.where(and(eq(dailyWords.dateStr, today), eq(dailyWords.mode, 'phrase')));

	if (!daily) return { error: 'NO_PHRASE_TODAY' as const };

	const target = normalizeSpanish(daily.word);
	// Normalizamos espacios múltiples y acentos para comparar justo la frase
	const cleanTarget = target.replace(/\s+/g, ' ').trim();
	const cleanGuess = normalizeSpanish(phraseGuessRaw).replace(/\s+/g, ' ').trim();

	if (!cleanGuess) return { error: 'EMPTY_GUESS' as const };

	const isCorrect = cleanGuess === cleanTarget;

	// Contar cuántas letras únicas faltaban por descubrir (para dar bono por resolver temprano)
	const uniqueTargetLetters = new Set(cleanTarget.split('').filter((c) => LETTER_REGEX.test(c)));

	// Flujo INVITADO
	if (!session) {
		const wrongLetters = guestLetters.filter((l) => !cleanTarget.includes(l));
		const totalMistakes = wrongLetters.length + guestWrongResolutions + (isCorrect ? 0 : 1);

		const won = isCorrect;
		const lost = !won && totalMistakes >= MAX_ATTEMPTS;
		const status = won ? 'won' : lost ? 'lost' : 'playing';

		const revealedCount = [...uniqueTargetLetters].filter((l) => guestLetters.includes(l)).length;
		const unrevealedBonus = Math.max(0, (uniqueTargetLetters.size - revealedCount) * 5);
		const score = won ? Math.min(150, Math.max(30, 100 - wrongLetters.length * 15 + unrevealedBonus)) : 0;

		return {
			ok: true as const,
			isCorrect,
			maskedChars: buildMaskedPhrase(cleanTarget, guestLetters, status !== 'playing'),
			guessedLetters: guestLetters,
			wrongLetters,
			wrongResolutions: guestWrongResolutions + (isCorrect ? 0 : 1),
			status,
			score,
			solution: status !== 'playing' ? cleanTarget : null
		};
	}

	// Flujo REGISTRADO (guarda en Supabase)
	let [attempt] = await db
		.select()
		.from(gameAttempts)
		.where(and(eq(gameAttempts.userId, session.user.id), eq(gameAttempts.wordId, daily.id)));

	if (!attempt) {
		[attempt] = await db
			.insert(gameAttempts)
			.values({ userId: session.user.id, wordId: daily.id, guesses: [] })
			.returning();
	}

	if (attempt.status !== 'playing') return { error: 'ALREADY_FINISHED' as const };

	const updatedGuesses = isCorrect ? attempt.guesses : [...attempt.guesses, `SOLVE:${cleanGuess}`];
	const letterGuesses = updatedGuesses.filter((g) => !g.startsWith('SOLVE:'));
	const wrongLetters = letterGuesses.filter((l) => !cleanTarget.includes(l));
	const wrongResolutions = updatedGuesses.filter((g) => g.startsWith('SOLVE:')).length;
	const totalMistakes = wrongLetters.length + wrongResolutions;

	const won = isCorrect;
	const lost = !won && totalMistakes >= MAX_ATTEMPTS;
	const status = won ? 'won' : lost ? 'lost' : 'playing';

	const revealedCount = [...uniqueTargetLetters].filter((l) => letterGuesses.includes(l)).length;
	const unrevealedBonus = Math.max(0, (uniqueTargetLetters.size - revealedCount) * 5);
	const score = won ? Math.min(150, Math.max(30, 100 - wrongLetters.length * 15 + unrevealedBonus)) : 0;

	await db
		.update(gameAttempts)
		.set({
			guesses: updatedGuesses,
			status,
			score,
			finishedAt: status !== 'playing' ? new Date() : null
		})
		.where(eq(gameAttempts.id, attempt.id));

	if (status !== 'playing') {
		await syncUserDailyStreak(session.user.id, today);
	}

	return {
		ok: true as const,
		isCorrect,
		maskedChars: buildMaskedPhrase(cleanTarget, letterGuesses, status !== 'playing'),
		guessedLetters: letterGuesses,
		wrongLetters,
		wrongResolutions,
		status,
		score,
		solution: status !== 'playing' ? cleanTarget : null
	};
}

export async function updateDisplayName(newName: string) {
	const session = await auth.api.getSession({ headers: await headers() });
	if (!session) return { error: 'UNAUTHENTICATED' as const };

	const cleaned = newName.trim().slice(0, 24);
	if (cleaned.length < 2) return { error: 'NAME_TOO_SHORT' as const };

	await db.update(user).set({ name: cleaned }).where(eq(user.id, session.user.id));
	return { ok: true as const };
}